المرحلة 3: تصميم واجهة الموقع — نظام ألوان متناسق، خطوط مناسبة، أحجام واضحة، مسافات منظمة، أزرار متناسقة، تنقل واضح، تجاوب، حالات تحميل وخطأ ونجاح وعدم وجود بيانات. احترافي، واضح، سريع، متجاوب، مناسب للمشروع، ومتوافق مع العربية وRTL. لا تنشئ واجهة عامة مكررة لجميع المشاريع؛ يجب أن يعكس التصميم هوية كل مشروع.

المرحلة 4: إنشاء صفحات الموقع — أنشئ الصفحات المطلوبة بالكامل (مثل: الرئيسية، الخدمات، المنتجات، تفاصيل المنتج، الأسعار، الدخول، إنشاء حساب، حساب المستخدم، التواصل، لوحة الإدارة). لا تنشئ صفحات غير مرتبطة بالمشروع. كل صفحة بمحتوى مناسب ووظائف حقيقية.

المرحلة 5: إنشاء Backend — بنية منظمة، API واضحة، تحقق من المدخلات، صلاحيات، معالجة أخطاء، منع الوصول غير المصرح، معالجة آمنة، توثيق، فصل منطق الأعمال، قابلية التوسع.

المرحلة 6: إنشاء قاعدة البيانات — الكيانات، العلاقات، أنواع البيانات، المفاتيح الأساسية والخارجية، القيود، الفهارس، سياسات الوصول، Migrations، سلامة البيانات. لا تضع بيانات المستخدمين أو الطلبات أو المدفوعات في ملفات ثابتة.

المرحلة 7: ربط الموقع — Frontend مع Backend، Backend مع قاعدة البيانات، الدخول مع المصادقة، لوحة الإدارة مع الصلاحيات، النماذج مع الحفظ، الأزرار مع الوظائف الحقيقية، الخدمات الخارجية مع واجهاتها الرسمية.

المرحلة 8: اختبار الموقع — الصفحات، الروابط، الأزرار، النماذج، الدخول والخروج، إنشاء الحساب، التعديل والحذف، الصلاحيات، قواعد البيانات، API، الجوال والكمبيوتر، السرعة، أخطاء Console وBackend. لا تعتبر الموقع جاهزاً لمجرد أنه يظهر في المتصفح.

المرحلة 9: تحسين الموقع — السرعة، ضغط الصور، SEO، الوصول، تجربة المستخدم، الأداء، الأمان، استهلاك الموارد.

المرحلة 10: نشر الموقع — متغيرات البيئة، قاعدة بيانات الإنتاج، الدومين، HTTPS، التخزين، النسخ الاحتياطية، سجلات الأخطاء، المراقبة، بيئة Production، الاختبار بعد النشر. لا تدّعِ أن الموقع منشور إذا لم تتم عملية النشر فعلياً.

