"use strict";
// New creation wizard: steps validate, optional info + items reach the saved brief and the template.
const { launch } = require('./mock');
const fs = require('fs');
const shots = process.argv[2];
let fails = 0; const check = (n, c) => { console.log((c ? 'PASS' : 'FAIL') + '  ' + n); if (!c) fails++; };
(async () => {
  const h = await launch({ role: 'customer', viewport: { width: 390, height: 844 }, rpc: { slug_available: true, request_publish: 'dep-1' }, functions: { 'ai-gateway': { ok: false, error: 'service_not_configured' }, 'verify-publish': { ok: true, url: 'https://x.pages.dev/royal' } }, tables: { websites: [], website_versions: [] } });
  const { page } = h;
  await h.open('#/app/new/form'); await page.waitForSelector('form[data-form="wizard"]');
  const step = () => page.evaluate(() => +document.querySelector('form[data-form="wizard"]').dataset.step);
  const next = async () => { await page.click('[data-act="wznext"]'); await page.waitForTimeout(120); };
  const shot = async (n) => { if (shots) { fs.mkdirSync(shots, { recursive: true }); await page.screenshot({ path: `${shots}/wz${n}.png` }); } };
  await shot(1);
  await next(); check('step 1 blocks until the idea is written', (await step()) === 1);
  await page.fill('textarea[name=desc]', 'محل ألعاب رياضية وتزلج'); await page.click('.tc:nth-child(2)'); await next(); check('moves to step 2', (await step()) === 2);
  await shot(2);
  await next(); check('step 2 blocks without a name', (await step()) === 2);
  await page.fill('input[name=name]', 'رويال سكيت'); await next(); check('step 2 blocks until the link is confirmed', (await step()) === 2);
  await page.fill('#sl', 'royalskate'); await page.waitForTimeout(700); await next(); check('moves to step 3', (await step()) === 3);
  await next(); check('step 3 blocks without a phone', (await step()) === 3);
  await page.fill('input[name=phone]', '0912345678'); await next(); await shot(4);
  const rows = page.locator('#wzitems .wzrow');
  await rows.nth(0).locator('[data-wi=n]').fill('حذاء تزلج'); await rows.nth(0).locator('[data-wi=p]').fill('150 د.ل'); await rows.nth(0).locator('[data-wi=d]').fill('مقاس 40-44');
  await page.click('[data-act="wzrowadd"]'); await page.locator('#wzitems .wzrow').nth(3).locator('[data-wi=n]').fill('خوذة');
  check('items compile to name|price|desc lines', (await page.locator('textarea[name=items]').inputValue()) === 'حذاء تزلج|150 د.ل|مقاس 40-44\nخوذة||');
  await next(); await shot(5);
  await page.fill('input[name=aud]', 'شباب طرابلس'); await page.selectOption('select[name=goal]', 'order'); await page.selectOption('select[name=tone]', 'youth');
  await page.fill('textarea[name=usp]', 'صيانة مجانية\nتوصيل داخل المدينة'); await page.fill('textarea[name=notes]', 'قسم للعروض');
  await next(); await shot(6); await next(); await shot(7);
  check('review lists the entered data', /رويال سكيت/.test(await page.locator('#wzsum').innerText()) && /royalskate/.test(await page.locator('#wzsum').innerText()));
  check('only the last step shows Create', await page.locator('#wzgo').isVisible() && await page.locator('[data-act="wznext"]').isHidden());
  await page.click('[data-act="wzprev"]'); check('back works', (await step()) === 6); await next();
  await page.click('#wzgo'); await page.waitForSelector('#bo.ok, #bo.err', { timeout: 15000 });
  const ins = h.calls.find((c) => c.method === 'POST' && /\/websites/.test(c.url));
  const br = ins && ins.body.config.brief;
  check('brief carries the optional info', br && br.aud === 'شباب طرابلس' && br.goal === 'order' && br.tone === 'youth' && /صيانة مجانية/.test(br.usp) && br.notes === 'قسم للعروض' && br.type === 'store');
  check('brief carries the items', br && /حذاء تزلج\|150 د\.ل\|مقاس 40-44/.test(br.items));
  const v = h.calls.find((c) => c.method === 'POST' && /website_versions/.test(c.url));
  check('template uses the selling points as "why us" cards', v && /صيانة مجانية/.test(v.body.snapshot.html) && /توصيل داخل المدينة/.test(v.body.snapshot.html));
  check('no page errors', h.errors.length === 0 || (console.log(h.errors), false));
  await h.close();
  process.exit(fails ? 2 : 0);
})();
